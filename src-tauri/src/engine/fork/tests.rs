    std::fs::write(&foreign, "别人的转录本\n").unwrap();

    let error = materialize_trimmed_fork(&db, "claude", source_id, target, usize::MAX)
        .expect_err("目标文件已存在时必须报错，绝不能复用它");
    assert!(error.contains("已被占用"), "报错要说清是路径冲突: {error}");
